CREATE TABLE IF NOT EXISTS rpm_purchase_order (
    purchase_order_id INT NOT NULL AUTO_INCREMENT,
    program VARCHAR(100) NOT NULL,
    facility_id INT NOT NULL,
    supplier_id INT NULL,
    total_cost DECIMAL(18,2) NOT NULL DEFAULT 0,
    requested_date DATETIME NOT NULL,
    requested_by INT NULL,
    approval_status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    approved_date DATETIME NULL,
    approved_by INT NULL,
    dispatch_status VARCHAR(50) NOT NULL DEFAULT 'PENDING_APPROVAL',
    dispatch_reference VARCHAR(255) NULL,
    creator INT NULL,
    date_created DATETIME NULL,
    voided TINYINT(1) NOT NULL DEFAULT 0,
    voided_by INT NULL,
    date_voided DATETIME NULL,
    void_reason VARCHAR(255) NULL,
    uuid CHAR(38) NOT NULL,
    PRIMARY KEY (purchase_order_id),
    UNIQUE INDEX rpm_purchase_order_uuid_idx (uuid),
    INDEX rpm_purchase_order_program_idx (program),
    INDEX rpm_purchase_order_status_idx (approval_status),
    INDEX rpm_purchase_order_dispatch_idx (dispatch_status)
);

CREATE TABLE IF NOT EXISTS rpm_purchase_order_item (
    purchase_order_item_id INT NOT NULL AUTO_INCREMENT,
    purchase_order_id INT NOT NULL,
    order_number VARCHAR(100) NOT NULL,
    program VARCHAR(100) NOT NULL,
    item_name VARCHAR(255) NOT NULL,
    item_code VARCHAR(100) NOT NULL,
    quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
    unit_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    total_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    creator INT NULL,
    date_created DATETIME NULL,
    voided TINYINT(1) NOT NULL DEFAULT 0,
    voided_by INT NULL,
    date_voided DATETIME NULL,
    void_reason VARCHAR(255) NULL,
    uuid CHAR(38) NOT NULL,
    PRIMARY KEY (purchase_order_item_id),
    UNIQUE INDEX rpm_purchase_order_item_uuid_idx (uuid),
    INDEX rpm_purchase_order_item_order_number_idx (order_number),
    INDEX rpm_purchase_order_item_purchase_order_idx (purchase_order_id)
);
